export type StringKey = keyof (typeof strings)['de']

export function makeT(language: Language) {
  const dict = strings[language] ?? strings.de
  return (key: StringKey, vars?: Record<string, string | number>) => {
    let value: string = dict[key] ?? strings.de[key] ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v))
    }
    return value
  }
}

export type Translate = ReturnType<typeof makeT>
